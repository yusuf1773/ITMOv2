test('ошибка сохранения оставляет результат и допускает повторную попытку', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Начать урок' }).click()
  await page.getByRole('button', { name: 'Следующее слово' }).click()
  await page.getByRole('button', { name: 'К правилу' }).click()
  await page.getByRole('button', { name: 'Теперь попробуем →' }).click()
  await page.getByRole('button', { name: 'книга' }).click()
  await page.getByRole('button', { name: 'Проверить' }).click()
  await page.getByRole('button', { name: 'Продолжить →' }).click()
  await page.getByRole('textbox', { name: 'Перевод на русский язык' }).fill('тетрадь')
  await page.getByRole('button', { name: 'Проверить' }).click()
  await page.getByRole('button', { name: 'Продолжить →' }).click()
  await page.getByRole('button', { name: 'китаплар' }).click()
  await page.getByRole('button', { name: 'Проверить' }).click()
  await page.evaluate(() => {
    const scopedWindow = window as typeof window & { originalSetItem?: Storage['setItem'] }
    scopedWindow.originalSetItem = Storage.prototype.setItem
    Storage.prototype.setItem = () => { throw new Error('quota') }
  })
  await page.getByRole('button', { name: 'Продолжить →' }).click()
  await expect(page.getByText('Не удалось сохранить результат. Он остаётся на экране.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Вернуться к курсу' })).toBeDisabled()
  await attachScreenshot(page, testInfo, '01 — ошибка сохранения')
  await page.evaluate(() => {
    const scopedWindow = window as typeof window & { originalSetItem?: Storage['setItem'] }
    Storage.prototype.setItem = scopedWindow.originalSetItem!
  })
  await page.getByRole('button', { name: 'Повторить сейчас' }).click()
  await expect(page.getByText('✓ Прогресс сохранён')).toBeVisible()
  await attachScreenshot(page, testInfo, '02 — сохранено после повтора')
})

