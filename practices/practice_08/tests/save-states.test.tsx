import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { expect, it, vi } from 'vitest'
import App from '@/App'

it('оставляет результат при ошибке сохранения и сохраняет после повторной попытки', async () => {
  const user = userEvent.setup()
  render(<App />)
  await screen.findByRole('heading', { name: 'Мой курс' })
  await user.click(screen.getByRole('button', { name: 'Начать урок' }))
  await user.click(screen.getByRole('button', { name: 'Следующее слово' }))
  await user.click(screen.getByRole('button', { name: 'К правилу' }))
  await user.click(screen.getByRole('button', { name: 'Теперь попробуем →' }))
  await user.click(screen.getByRole('button', { name: 'книга' }))
  await user.click(screen.getByRole('button', { name: 'Проверить' }))
  await user.click(screen.getByRole('button', { name: 'Продолжить →' }))
  await user.type(screen.getByRole('textbox', { name: 'Перевод на русский язык' }), 'тетрадь')
  await user.click(screen.getByRole('button', { name: 'Проверить' }))
  await user.click(screen.getByRole('button', { name: 'Продолжить →' }))
  await user.click(screen.getByRole('button', { name: 'китаплар' }))
  await user.click(screen.getByRole('button', { name: 'Проверить' }))

  const write = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
  await user.click(screen.getByRole('button', { name: 'Продолжить →' }))
  expect(await screen.findByText('Не удалось сохранить результат. Он остаётся на экране.')).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Вернуться к курсу' })).toBeDisabled()
  expect(write).toHaveBeenCalledTimes(2)
  write.mockRestore()
  await user.click(screen.getByRole('button', { name: 'Повторить сейчас' }))
  await waitFor(() => expect(screen.getByText('✓ Прогресс сохранён')).toBeInTheDocument())
  await user.click(screen.getByRole('button', { name: 'Вернуться к курсу' }))
  expect(screen.getByText('Пройдено 1 из 3 уроков')).toBeInTheDocument()
})

it('не сохраняет результат повторно при нажатиях во время ожидания', async () => {
  const user = userEvent.setup()
  render(<App />)
  await screen.findByRole('heading', { name: 'Мой курс' })
  await user.click(screen.getByRole('button', { name: 'Начать урок' }))
  await user.click(screen.getByRole('button', { name: 'Следующее слово' }))
  await user.click(screen.getByRole('button', { name: 'К правилу' }))
  await user.click(screen.getByRole('button', { name: 'Теперь попробуем →' }))
  await user.click(screen.getByRole('button', { name: 'книга' }))
  await user.click(screen.getByRole('button', { name: 'Проверить' }))
  await user.click(screen.getByRole('button', { name: 'Продолжить →' }))
  await user.type(screen.getByRole('textbox', { name: 'Перевод на русский язык' }), 'тетрадь')
  await user.click(screen.getByRole('button', { name: 'Проверить' }))
  await user.click(screen.getByRole('button', { name: 'Продолжить →' }))
  await user.click(screen.getByRole('button', { name: 'китаплар' }))
  await user.click(screen.getByRole('button', { name: 'Проверить' }))

  const storage = await import('@/storage/progress')
  let finishSave!: (progress: ReturnType<typeof storage.emptyProgress>) => void
  const save = vi.spyOn(storage, 'saveResult').mockImplementation(() => new Promise(resolve => { finishSave = resolve }))
  await user.click(screen.getByRole('button', { name: 'Продолжить →' }))
  await waitFor(() => expect(save).toHaveBeenCalledTimes(1))
  expect(screen.getByText('Сохраняем прогресс…')).toBeInTheDocument()
  const back = screen.getByRole('button', { name: 'Вернуться к курсу' })
  expect(back).toBeDisabled()
  await user.dblClick(back)
  await user.keyboard('{Enter}')
  expect(save).toHaveBeenCalledTimes(1)
  finishSave(storage.applyResult(storage.emptyProgress(), save.mock.calls[0][0]))
  await waitFor(() => expect(screen.getByText('✓ Прогресс сохранён')).toBeInTheDocument())
  save.mockRestore()
})
