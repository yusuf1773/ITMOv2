import { expect, test, type Page, type TestInfo } from '@playwright/test'

async function attachScreenshot(page: Page, testInfo: TestInfo, name: string) {
  await testInfo.attach(name, { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
}

async function finishFirstLesson(page: Page) {
  await page.getByRole('button', { name: 'Начать урок' }).click()
  await page.getByRole('button', { name: 'Следующее слово' }).click()
  await page.getByRole('button', { name: 'К правилу' }).click()
  await expect(page.getByRole('heading', { name: 'Множественное число' })).toBeVisible()
  await page.getByRole('button', { name: 'Теперь попробуем →' }).click()
  await page.getByRole('button', { name: 'книга' }).click()
  await page.getByRole('button', { name: 'Проверить' }).click()
  await page.getByRole('button', { name: 'Продолжить →' }).click()
  await page.getByRole('textbox', { name: 'Перевод на русский язык' }).fill('ТЕТРАДЬ')
  await page.getByRole('textbox', { name: 'Перевод на русский язык' }).press('Enter')
  await expect(page.getByText('Верно!')).toBeVisible()
  await page.getByRole('button', { name: 'Продолжить →' }).click()
  await page.getByRole('button', { name: 'китаплар' }).click()
  await page.getByRole('button', { name: 'Проверить' }).click()
  await page.getByRole('button', { name: 'Продолжить →' }).click()
  await expect(page.getByRole('heading', { name: 'Урок завершён!' })).toBeVisible()
}

test('урок сохраняется и открывает следующий после перезагрузки', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.getByText('Пройдено 0 из 3 уроков')).toBeVisible()
  await attachScreenshot(page, testInfo, '01 — главный экран')
  await finishFirstLesson(page)
  await expect(page.getByText('✓ Прогресс сохранён')).toBeVisible()
  await attachScreenshot(page, testInfo, '02 — итог урока')
  await page.getByRole('button', { name: 'Вернуться к курсу' }).click()
  await page.reload()
  await expect(page.getByText('Пройдено 1 из 3 уроков')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Начать урок' })).toBeEnabled()
  await attachScreenshot(page, testInfo, '03 — сохранённый прогресс')
})

